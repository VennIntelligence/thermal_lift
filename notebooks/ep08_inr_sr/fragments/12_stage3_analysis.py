# ## 11. 方法适用性分析 — 为什么 INR/DIP 在此任务上表现不佳
#
# Stage 3 的结果揭示了一个根本性问题：**三种深度 prior 方法（SIREN、WIRE、
# DeepInverse-DIP）的归纳偏置（inductive bias）与工业芯片热像的几何结构
# 严重不匹配**。以下从物理和数学角度分析原因。
#
# ---
#
# ### 11.1 SIREN — 正弦激活导致的几何扭曲
#
# SIREN 用 $\sin(\omega \cdot \mathbf{W}\mathbf{x} + \mathbf{b})$ 作为每层激活函数，
# 本质上把 HR 图像表示为**一组正弦基函数的复合**。
#
# - **对自然图像有效**：自然纹理（树叶、皮肤、云彩）没有严格的直线/直角约束，
#   正弦基函数的平滑组合能很好地拟合这类有机形状。
# - **对工业几何致命**：芯片的物理边缘是直线、直角、规则矩形。用正弦函数
#   逼近一条直线边缘时，必然产生 **Gibbs 振荡**——网络越想锐化边缘，
#   振铃/波浪越明显。这就是我们看到 SIREN 把平直轮廓扭成波浪形的数学原因。
# - **split-half 退化**：0.225 的 split-half NRMSE 说明两个帧子集给出的
#   波浪形状不一致——波浪的具体形态取决于训练帧的随机组合，而不是物理真实结构。
#
# ### 11.2 WIRE — Gabor 激活的同类问题
#
# WIRE 使用 Gabor 小波 $\sin(\omega x) \cdot \exp(-x^2/\sigma^2)$ 作为激活，
# 是 **局部化的振荡函数**。
#
# - Gabor 基函数设计用于**纹理表示**（与 V1 简单细胞感受野匹配），
#   擅长捕捉方向性纹理和局部频率，但不擅长表示长程直线边缘。
# - 相比 SIREN，WIRE 的边缘响应更强（p95_gradient 更高），
#   但波浪扭曲程度类似，因为 Gabor 核本质上仍是振荡函数。
# - split-half NRMSE (0.193) 略好于 SIREN (0.225)，
#   但仍远差于 MAP-TV (0.044)。
#
# ### 11.3 DeepInverse-DIP — CNN 解码器的幻觉问题
#
# DIP 用 CNN 解码器架构作为隐式 prior：从固定随机 latent 出发，
# 优化网络权重使输出通过 forward model 后拟合观测帧。
#
# - **为什么几何更直**：CNN 的卷积核（3×3 等）天然沿行列方向操作，
#   不像 sin/Gabor 那样引入振荡性几何扭曲。所以 DIP 输出中的直线确实更直。
# - **为什么全是噪声**：CNN decoder 的参数量远大于所需表示的复杂度。
#   在 15,000 步训练后，网络有足够容量**记忆噪声**。
#   本任务中有用的亚像素位移信号极其微弱（max 4 像素位移，
#   0.0724°C 噪声底），CNN 很快就超过了提取有用信号的阶段，
#   开始用纹理幻觉填充背景。
# - **split-half NRMSE 0.512**：这是所有方法中最差的，
#   意味着两个帧子集给出**完全不同的重建**——纯噪声拟合。
# - **artifact_score ≈ 1.0**：远高于其他方法（MAP-TV: 0.027），
#   确认了高频伪纹理的存在。
#
# ### 11.4 MAP-TV — 为什么经典方法在此任务上最优
#
# MAP-TV 最小化 $\|\mathbf{A}\mathbf{x} - \mathbf{y}\|^2 + \lambda_{\mathrm{TV}} \|\nabla \mathbf{x}\|_1$，
# 其中 TV 正则化施加 **L1 梯度惩罚**。
#
# - **L1 梯度 = 分段常数 prior**：TV 正则化天然偏好分段常数图像——
#   平坦区域 + 锐利边缘。这**几乎完美匹配**芯片热像的物理结构
#   （均匀温度区域被锐利的几何边界分隔）。
# - **不引入振荡**：没有正弦/Gabor 基函数，不会产生 Gibbs 波浪。
# - **凸优化 → 唯一解 → 稳定**：split-half NRMSE 0.044，
#   远低于所有深度方法。两个帧子集给出几乎相同的重建。
# - **保守但正确**：p95_gradient (0.090) 低于 SIREN (0.070)
#   和 WIRE (0.100)，说明 TV 的边缘偏平滑/保守。
#   但保守 + 正确 > 激进 + 扭曲。
#
# ### 11.5 根本教训
#
# | 维度 | INR (SIREN/WIRE) | DIP (CNN decoder) | MAP-TV |
# |------|------------------|-------------------|--------|
# | **基函数** | 正弦/Gabor 振荡 | 卷积纹理 | 梯度稀疏 |
# | **对直线边缘** | 波浪扭曲 (Gibbs) | 相对保持 | 锐利保持 |
# | **对平坦区域** | 可拟合 | 噪声填充 | 强制平坦 |
# | **稳定性** | 中 (0.19–0.22) | 差 (0.51) | 优 (0.04) |
# | **适合场景** | 自然纹理/有机形状 | 自然图像修复 | 工业/几何结构 |
#
# **核心结论**: 重建 prior 的归纳偏置必须匹配场景的几何结构。
# 工业芯片检测 = 分段常数 + 几何边缘 → TV-class prior 天然适配；
# 振荡基函数 (INR) 和纹理生成器 (DIP) 引入了错误的复杂性。
#
# ---
#
# ### 11.6 对项目的影响
#
# 1. **Stage 3 的 contour-level POC 应以 MAP-TV 为核心方法**，
#    而非尝试让 INR/DIP 适配工业几何。
# 2. 后续优化方向：
#    - λ_TV 调优和 PSF 精化
#    - Total Generalized Variation (TGV) 或各向异性 TV，
#      更好地保持角点和细长结构
#    - 多尺度/金字塔重建
# 3. SIREN/WIRE/DIP 的实验价值在于**作为反面对照**，
#    证明并非所有 SR 方法都能在此场景下工作，
#    从而凸显 prior 选择的重要性。

