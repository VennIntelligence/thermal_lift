# > **数据分布**: 主 session 有 255 帧，其中主体是 R=0 raster 网格；行内 X 转移数量远多于换行转移，符合逐行扫描模式。
# > **核心发现**: EP02 后续所有 pair 选择都应先区分“坐标相邻”和“采集时间相邻”。这个边界比单个 NCC、ESF 或相位相关结果更基础。
