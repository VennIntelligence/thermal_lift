# %% [markdown]
# > **图表说明**: 左上图按 `acquisition_order` 给主 session R=0 坐标连线，底部时间线分别展示 X/Y 随采集顺序的变化，右上图标出 R=0 网格覆盖。
# > **怎么读图**: 连线方向表示真实采集时间推进，不表示图像内容的位移估计。若 X 时间线呈一段段斜坡、Y 时间线呈阶梯，就说明相机/电动台按 raster 路径逐行扫描。
# > **正常/异常理解**: 正常的 raster 应表现为 X 在每条扫描线内连续前进，换行时回到下一行起点；Y 只在换行处阶梯式增加。若按文件名字母序作图，会得到伪造的跳变路径，这是后续对齐诊断的常见污染源。
# > **数据分布**: 少量 R=0 点缺失，但主网格覆盖仍提供全局坐标云。关键不是“网格是否完美”，而是“哪些 pair 真实时间相邻”。
# > **核心发现**: TXT/BMP 主数据是 step-and-shoot raster 采集。X 行内相邻点是真正时间相邻，固定 X 的 Y 坐标相邻点通常隔了一整行采集时间，因此不能把二者当成同等质量的位移样本。

