# 对不熟悉本数据的人来说，最容易犯的错误是把文件名排序当成拍摄顺序。这里的 `X_Y_R` 只说明电动台命令坐标和重复编号，不说明这张图是在什么时候拍的。
# 因此，判断“相邻帧”必须使用 `acquisition_order`：只有采集顺序相邻，才有资格被当作短时间位移诊断；只是在坐标上相邻，仍可能隔了很多帧。

